// ---------- 取り込み(名刺・署名):メール・電話・会社名らしき行だけを機械的に拾う ----------
export function demoExtract(text) {
  const lines = text.split(/\n/).map((l) => l.trim()).filter(Boolean);
  const email = text.match(/[^\s@/]+@[^\s@/]+\.[^\s@/]+/)?.[0] ?? "";
  const phone = text.match(/0\d{1,4}-\d{1,4}-\d{3,4}/)?.[0] ?? "";
  const companyLine = lines.find((l) => /株式会社|\(株\)|(株)|有限会社|合同会社/.test(l)) ?? "";
  const nameLine = lines.find((l) => l !== companyLine && !l.includes("@") && !/\d{2,}/.test(l) && /^[^\s]{1,6}[\s ][^\s]{1,6}$/.test(l)) ?? "";
  return {
    companies: companyLine ? [{ name: companyLine, industry: "", tier: "", website: "", notes: "" }] : [],
    contacts: nameLine ? [{ companyName: companyLine, name: nameLine, title: "", department: "", email, phone, role: "不明" }] : [],
    deals: [],
    demo: true,
  };
}
